export type PrepCard = {
  id: string
  prompt: string
  ja: string
  answer: string
  accept: string[]
  choices: string[]
  tip: string
}

function prep(
  id: string,
  prompt: string,
  ja: string,
  answer: string,
  choices: string[],
  tip: string,
  accept: string[] = [answer],
): PrepCard {
  return { id, prompt, ja, answer, accept, choices, tip }
}

